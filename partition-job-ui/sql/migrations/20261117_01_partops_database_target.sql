-- =============================================================================
-- Migration: Phase 5C (part 1) — hub-local database target registry
-- =============================================================================
-- PREPARED ONLY — do NOT auto-apply to production. Apply in a DBA window with
-- the scheduler STOPPED, after 20261110_03.
--
-- Architecture (one PartOps installation per hub, ~2 databases per hub; NO
-- global multi-hub control plane):
--
--   CONTROL DATABASE  = the database this migration runs in (the existing
--                       PartOps database). Holds the job definitions, the
--                       target registry, attention items, history, version.
--   MANAGED TARGETS   = databases whose partitions PartOps maintains. The
--                       control database is itself the DEFAULT target
--                       (is_control_database = TRUE, key 'db01'). Further
--                       targets (e.g. 'db02') are registered by a DBA.
--
-- Creates:
--   * mubasher_oms.partops_database_target  (registry; NO passwords / keys /
--     secret values — only an AWS Secrets Manager secret IDENTIFIER)
--   * mubasher_oms.partops_control_target_id()  (id of the control target)
--   * partitioning_job_table.database_target_id  (backfilled to the control
--     target, then NOT NULL + DEFAULT + FK). Existing jobs keep their schedule
--     and configuration unchanged; the legacy insert function keeps working
--     because new rows default to the control target.
--
-- Registry writes are DBA-only in Phase 5C (app roles: SELECT only).
-- Idempotent: safe to re-run.
--
-- Rollback (only after 20261117_02 has been rolled back):
--   ALTER TABLE mubasher_oms.partitioning_job_table
--       DROP CONSTRAINT IF EXISTS partitioning_job_table_target_fk,
--       ALTER COLUMN database_target_id DROP DEFAULT;
--   ALTER TABLE mubasher_oms.partitioning_job_table DROP COLUMN IF EXISTS database_target_id;
--   DROP FUNCTION IF EXISTS mubasher_oms.partops_control_target_id();
--   DROP TABLE IF EXISTS mubasher_oms.partops_database_target;
-- =============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- 1. Target registry
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mubasher_oms.partops_database_target (
    target_id            integer GENERATED BY DEFAULT AS IDENTITY,
    target_key           character varying(32) NOT NULL,
    display_name         character varying(100) NOT NULL,
    -- NULL host/port = "connect like the control database" (process env).
    host                 character varying(255),
    port                 integer,
    database_name        character varying(63) NOT NULL,
    -- inherit = process default credentials (control target);
    -- aws = this target's own Secrets Manager secret (fail closed);
    -- env = local development only (PARTOPS_TARGET_<KEY>_DB_USER/_PASSWORD).
    credential_provider  character varying(10) NOT NULL DEFAULT 'inherit',
    secret_id            character varying(512),
    aws_region           character varying(32),
    ssl_mode             character varying(16),
    environment          character varying(32),
    is_enabled           boolean NOT NULL DEFAULT TRUE,
    is_control_database  boolean NOT NULL DEFAULT FALSE,
    max_concurrent_jobs  smallint NOT NULL DEFAULT 1,
    created_at           timestamp without time zone NOT NULL
        DEFAULT (clock_timestamp()::timestamp without time zone),
    updated_at           timestamp without time zone NOT NULL
        DEFAULT (clock_timestamp()::timestamp without time zone),
    CONSTRAINT partops_database_target_pkey PRIMARY KEY (target_id),
    CONSTRAINT partops_database_target_key_uq UNIQUE (target_key),
    CONSTRAINT partops_database_target_key_ck
        CHECK (target_key ~ '^[a-z][a-z0-9_]{0,31}$'),
    CONSTRAINT partops_database_target_dbname_ck
        CHECK (database_name ~ '^[A-Za-z_][A-Za-z0-9_$-]{0,62}$'),
    CONSTRAINT partops_database_target_port_ck
        CHECK (port IS NULL OR port BETWEEN 1 AND 65535),
    CONSTRAINT partops_database_target_host_ck
        CHECK (host IS NULL OR host ~ '^[A-Za-z0-9][A-Za-z0-9.:_-]{0,254}$'),
    CONSTRAINT partops_database_target_remote_host_ck
        CHECK (is_control_database OR host IS NOT NULL),
    CONSTRAINT partops_database_target_provider_ck
        CHECK (credential_provider IN ('inherit', 'env', 'aws')),
    -- Identifier only (name or ARN characters) — never a JSON/secret value.
    CONSTRAINT partops_database_target_secret_ck
        CHECK (secret_id IS NULL OR secret_id ~ '^[A-Za-z0-9/_+=.@:-]+$'),
    CONSTRAINT partops_database_target_aws_ck
        CHECK (credential_provider <> 'aws' OR secret_id IS NOT NULL),
    CONSTRAINT partops_database_target_region_ck
        CHECK (aws_region IS NULL OR aws_region ~ '^[a-z]{2}(-[a-z]+)+-[0-9]$'),
    CONSTRAINT partops_database_target_ssl_ck
        CHECK (ssl_mode IS NULL OR ssl_mode IN
               ('disable', 'allow', 'prefer', 'require', 'verify-ca', 'verify-full')),
    CONSTRAINT partops_database_target_conc_ck
        CHECK (max_concurrent_jobs BETWEEN 1 AND 10)
);

COMMENT ON TABLE mubasher_oms.partops_database_target IS
    'Hub-local registry of databases this PartOps installation manages. The row '
    'with is_control_database = TRUE is this database (default target). Holds '
    'connection identity only — never passwords, access keys or secret values.';
COMMENT ON COLUMN mubasher_oms.partops_database_target.secret_id IS
    'AWS Secrets Manager secret IDENTIFIER (name/ARN) — not the secret value.';
COMMENT ON COLUMN mubasher_oms.partops_database_target.max_concurrent_jobs IS
    'Per-target concurrency cap (conservative default 1; enforced from Phase 5D).';

-- At most one control database row.
CREATE UNIQUE INDEX IF NOT EXISTS partops_database_target_one_control_uq
    ON mubasher_oms.partops_database_target (is_control_database)
    WHERE is_control_database;

ALTER TABLE mubasher_oms.partops_database_target OWNER TO mubasher_oms;
REVOKE ALL ON TABLE mubasher_oms.partops_database_target FROM PUBLIC;

-- ----------------------------------------------------------------------------
-- 2. Default (control) target = this database
-- ----------------------------------------------------------------------------
INSERT INTO mubasher_oms.partops_database_target
    (target_key, display_name, database_name, credential_provider,
     is_control_database, max_concurrent_jobs)
SELECT 'db01', 'DB-01 (control database)', current_database(), 'inherit', TRUE, 1
 WHERE NOT EXISTS (
        SELECT 1 FROM mubasher_oms.partops_database_target t
         WHERE t.is_control_database);

DO $$
DECLARE
    v_db text;
BEGIN
    SELECT t.database_name INTO v_db
      FROM mubasher_oms.partops_database_target AS t
     WHERE t.is_control_database;
    IF v_db IS DISTINCT FROM current_database() THEN
        RAISE EXCEPTION
            'Control target database_name % does not match current_database() %',
            v_db, current_database();
    END IF;
END
$$;

CREATE OR REPLACE FUNCTION mubasher_oms.partops_control_target_id()
RETURNS integer
LANGUAGE sql
STABLE
AS $function$
    SELECT t.target_id
      FROM mubasher_oms.partops_database_target AS t
     WHERE t.is_control_database
$function$;

COMMENT ON FUNCTION mubasher_oms.partops_control_target_id() IS
    'target_id of the control database (default target). NULL if not registered.';

ALTER FUNCTION mubasher_oms.partops_control_target_id() OWNER TO mubasher_oms;
REVOKE ALL ON FUNCTION mubasher_oms.partops_control_target_id() FROM PUBLIC;

-- ----------------------------------------------------------------------------
-- 3. Jobs reference a target: add → backfill → verify → enforce
-- ----------------------------------------------------------------------------
ALTER TABLE mubasher_oms.partitioning_job_table
    ADD COLUMN IF NOT EXISTS database_target_id integer;

UPDATE mubasher_oms.partitioning_job_table AS j
   SET database_target_id = mubasher_oms.partops_control_target_id()
 WHERE j.database_target_id IS NULL;

DO $$
DECLARE
    v_orphans bigint;
BEGIN
    SELECT count(*) INTO v_orphans
      FROM mubasher_oms.partitioning_job_table AS j
     WHERE j.database_target_id IS NULL
        OR NOT EXISTS (SELECT 1 FROM mubasher_oms.partops_database_target AS t
                        WHERE t.target_id = j.database_target_id);
    IF v_orphans <> 0 THEN
        RAISE EXCEPTION 'Target backfill incomplete: % job row(s) without a valid target', v_orphans;
    END IF;
END
$$;

-- New rows (incl. the legacy insert function, which is unaware of targets)
-- default to the control target. NULL control target ⇒ NOT NULL violation
-- (fails closed).
ALTER TABLE mubasher_oms.partitioning_job_table
    ALTER COLUMN database_target_id SET DEFAULT mubasher_oms.partops_control_target_id(),
    ALTER COLUMN database_target_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'partitioning_job_table_target_fk'
           AND conrelid = 'mubasher_oms.partitioning_job_table'::regclass
    ) THEN
        EXECUTE 'ALTER TABLE mubasher_oms.partitioning_job_table '
                'ADD CONSTRAINT partitioning_job_table_target_fk '
                'FOREIGN KEY (database_target_id) '
                'REFERENCES mubasher_oms.partops_database_target (target_id) '
                'ON UPDATE RESTRICT ON DELETE RESTRICT NOT VALID';
        EXECUTE 'ALTER TABLE mubasher_oms.partitioning_job_table '
                'VALIDATE CONSTRAINT partitioning_job_table_target_fk';
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS partitioning_job_table_target_idx
    ON mubasher_oms.partitioning_job_table (database_target_id);

COMMENT ON COLUMN mubasher_oms.partitioning_job_table.database_target_id IS
    'Managed database that receives this job''s partition operation '
    '(partops_database_target). Defaults to the control database.';

-- ----------------------------------------------------------------------------
-- 4. Narrow grants (read-only for app roles)
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'partition_job_ui') THEN
        EXECUTE 'GRANT SELECT ON mubasher_oms.partops_database_target TO partition_job_ui';
        EXECUTE 'GRANT EXECUTE ON FUNCTION mubasher_oms.partops_control_target_id() TO partition_job_ui';
    ELSE
        RAISE NOTICE 'Role partition_job_ui does not exist — grants skipped.';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'partition_job_scheduler') THEN
        EXECUTE 'GRANT SELECT ON mubasher_oms.partops_database_target TO partition_job_scheduler';
        EXECUTE 'GRANT EXECUTE ON FUNCTION mubasher_oms.partops_control_target_id() TO partition_job_scheduler';
    ELSE
        RAISE NOTICE 'Role partition_job_scheduler does not exist — grants skipped.';
    END IF;
END
$$;

COMMIT;

